/**
 * Staging root. Files, not tables — see the header: nothing unverified reaches
 * the DB. Read from the environment on every call rather than captured once, so
 * the test suite can point it at a temp directory and never touch the repo's
 * `data/` (the same discipline `tests/golden.test.ts` keeps with `:memory:`).
 */
export function draftsDir(): string {
  return process.env.GOLDEN_DRAFTS_DIR ?? DEFAULT_DRAFTS_DIR;
}

export function cardDir(oracleId: string): string {
  return join(draftsDir(), oracleId);
}
/**
 * The atom vocabulary, written ONCE per drafting session rather than inlined
 * into all ~125 packets: it is ~70 KB and identical in every one of them, and a
 * drafter working card by card should pay for it once. Regenerated by `--packet`
 * on every run, so a schema-version promotion cannot leave a stale copy behind.
 */
export const vocabularyPath = () => join(draftsDir(), 'vocabulary.json');
export const packetPath = (id: string) => join(cardDir(id), 'packet.json');
export const lookupsPath = (id: string) => join(cardDir(id), 'lookups.jsonl');
export const proposalPath = (id: string) => join(cardDir(id), 'proposal.json');
export const reviewPath = (id: string) => join(cardDir(id), 'review.json');

// --------------------------------------------------------------------------- packet

/** One rule as the drafter sees it: number plus its full parsed text. */
export interface PacketRule {
  number: string;
  section_number: string;
  subsection_title: string | null;
  text: string;
  /** Which matched term surfaced this rule, for traceability. */
  via: string[];
}

export interface PacketFace {
  face_index: number;
  name: string;
  oracle_text: string;
  clauses: Array<{ clause_index: number; kind: string; span_start: number; span_end: number; text: string }>;
}

/**
 * Everything a drafter is permitted to read for one card. Assembled from the
 * UNGATED corpus: `matchTerms` over the full `rule_term_index`, never
 * `assemblePacket`. If this ever starts reading the gated packet, the golden set
 * stops being able to audit the gate (sec. 3.6) — that is the one line here that
 * must not move.
 */
export interface DraftingPacket {
  oracle_id: string;
  name: string;
  layout: string;
  rarity: string;
  type_line: string;
  oracle_hash: string;
  schema_version: number;
  corpus_id: number;
  generated_at: string;
  faces: PacketFace[];
  /** Ungated term matches, with the glossary definition when the match came from one. */
  term_matches: Array<{ term: string; source: string; surface: string; rule_numbers: string[]; definition: string | null }>;
  /**
   * Full text of every rule the ungated term match reached, plus the subsection
   * body of any matched rule whose own text is an empty header.
   */
  rules: PacketRule[];
  /**
   * Numbers the term index reached that are NOT `rules` rows (section numbers
   * like 110 or 601). Not citable — listed so the drafter looks the section up
   * rather than assuming the packet had nothing to say about the term.
   */
  unresolved_references: Array<{ number: string; via: string[] }>;
  /** Where the shared vocabulary lives. No fit in it -> record unclassified, never force one. */
  vocabulary_path: string;
  vocabulary_count: number;
}

/** One entry of the atom vocabulary at a given schema_version. */
export interface VocabularyEntry {
  family: string;
  type_key: string;
  label: string;
  params_schema: unknown;
}

export function buildVocabulary(db: DatabaseSync): VocabularyEntry[] {
  const schemaVersion = currentSchemaVersion(db);
  return (
    db
      .prepare('SELECT family, type_key, label, params_schema FROM atom_types WHERE schema_version = ? ORDER BY family, type_key')
      .all(schemaVersion) as Array<{ family: string; type_key: string; label: string; params_schema: string }>
  ).map((t) => ({
    family: t.family,
    type_key: t.type_key,
    label: t.label,
    params_schema: JSON.parse(t.params_schema) as unknown,
  }));
}

export function writeVocabulary(db: DatabaseSync): { path: string; count: number } {
  mkdirSync(draftsDir(), { recursive: true });
  const entries = buildVocabulary(db);
  const path = vocabularyPath();
  writeFileSync(
    path,
    JSON.stringify({ schema_version: currentSchemaVersion(db), count: entries.length, types: entries }, null, 2) + '\n',
    'utf8',
  );
  return { path, count: entries.length };
}

export function buildDraftingPacket(db: DatabaseSync, oracleId: string): DraftingPacket {
  const card = db
    .prepare('SELECT name, layout, rarity, type_line, oracle_hash FROM cards WHERE oracle_id = ?')
    .get(oracleId) as
    | { name: string; layout: string; rarity: string; type_line: string; oracle_hash: string }
    | undefined;
  if (!card) throw new Error(`no card with oracle_id ${oracleId}`);

  const corpusId = currentCorpusId(db);
  const schemaVersion = currentSchemaVersion(db);

  const faceRows = db
    .prepare('SELECT face_index, name, oracle_text FROM card_faces WHERE oracle_id = ? ORDER BY face_index')
    .all(oracleId) as Array<{ face_index: number; name: string; oracle_text: string }>;

  const faces: PacketFace[] = faceRows.map((f) => ({
    face_index: f.face_index,
    name: f.name,
    oracle_text: f.oracle_text,
    clauses: splitOracleText(f.oracle_text, f.face_index).map((c) => ({
      clause_index: c.clause_index,
      kind: c.kind,
      span_start: c.span_start,
      span_end: c.span_end,
      text: c.text,
    })),
  }));

  // UNGATED: the full rule_term_index, not the assembled packet (sec. 8.1).
  const policy = loadPacketPolicy();
  const { text } = cardMatchText(db, oracleId);
  const matched = matchTerms(db, corpusId, text, policy);

  const via = new Map<string, Set<string>>();
  for (const m of matched) {
    for (const n of m.rule_numbers) {
      const set = via.get(n) ?? new Set<string>();
      set.add(m.term);
      via.set(n, set);
    }
  }
  const ruleStmt = db.prepare(
    'SELECT number, section_number, subsection_title, text FROM rules WHERE corpus_id = ? AND number = ?',
  );
  // A matched number is frequently a bare SUBSECTION HEADER whose own `text` is
  // empty — 702.19 "Trample" carries nothing; 702.19a..e carry the ability. A
  // packet that offered only the header would hand the drafter a citable number
  // with no readable content behind it, which is the one thing this whole design
  // is trying to prevent. Pull the body in when the header is empty. Capped,
  // because a term can match a large subsection and the packet is meant to be read.
  // Keyed on the PARSED `subsection_number`, never a `number LIKE '702.19%'`
  // prefix: that prefix also matches 702.190 through 702.194 (Sneak, Increment,
  // Paradigm, Power-up, Teamwork), which would put five unrelated keyword
  // abilities into a Trample packet and make them citable under the read gate.
  const childStmt = db.prepare(
    `SELECT number, section_number, subsection_title, text FROM rules
      WHERE corpus_id = ? AND subsection_number = ? AND number <> ? ORDER BY ordinal LIMIT ?`,
  );
  const CHILD_LIMIT = 40;
  const rules: PacketRule[] = [];
  const unresolved: Array<{ number: string; via: string[] }> = [];

  for (const number of [...via.keys()].sort()) {
    const viaTerms = [...(via.get(number) ?? [])].sort();
    const r = ruleStmt.get(corpusId, number) as
      | { number: string; section_number: string; subsection_title: string | null; text: string }
      | undefined;
    if (!r) {
      // The term index reaches a SECTION number (110, 601, ...) that is not itself
      // a `rules` row. It is therefore not citable either (`ruleNumbersExist`
      // rejects it), so say so rather than dropping it silently — the drafter
      // needs to look up the section body to cite anything from it.
      unresolved.push({ number, via: viaTerms });
      continue;
    }
    rules.push({ ...r, via: viaTerms });
    if (r.text.trim().length > 0) continue;
    const kids = childStmt.all(corpusId, number, number, CHILD_LIMIT) as Array<{
      number: string; section_number: string; subsection_title: string | null; text: string;
    }>;
    for (const k of kids) rules.push({ ...k, via: [`${number} (subsection body)`] });
  }

  const vocabulary = writeVocabulary(db);

  return {
    oracle_id: oracleId,
    name: card.name,
    layout: card.layout,
    rarity: card.rarity,
    type_line: card.type_line,
    oracle_hash: card.oracle_hash,
    schema_version: schemaVersion,
    corpus_id: corpusId,
    generated_at: new Date().toISOString(),
    faces,
    term_matches: matched.map((m) => ({
      term: m.term,
      source: m.source,
      surface: m.surface,
      rule_numbers: m.rule_numbers,
      definition: m.definition ?? null,
    })),
    rules,
    unresolved_references: unresolved,
    vocabulary_path: vocabulary.path,
    vocabulary_count: vocabulary.count,
  };
}

export function writePacket(packet: DraftingPacket): string {
  mkdirSync(cardDir(packet.oracle_id), { recursive: true });
  const path = packetPath(packet.oracle_id);
  writeFileSync(path, JSON.stringify(packet, null, 2) + '\n', 'utf8');
  return path;
}

export function readPacket(oracleId: string): DraftingPacket | undefined {
  const path = packetPath(oracleId);
  if (!existsSync(path)) return undefined;
  return JSON.parse(readFileSync(path, 'utf8')) as DraftingPacket;
}

// --------------------------------------------------------------------------- lookups

/** One corpus read the drafter performed, beyond what the packet already contained. */
export interface LookupRecord {
  at: string;
  kind: 'rule' | 'search' | 'glossary';
  query: string;
  /** Rule numbers whose text was returned — these become citable. */
  returned: string[];
}

/**
 * Appends one read to the card's audit log. Append-only on purpose: the log is
 * evidence that a citation came from the corpus rather than from model memory,
 * and evidence you can rewrite is not evidence.
 */
export function recordLookup(oracleId: string, rec: Omit<LookupRecord, 'at'>): void {
  mkdirSync(cardDir(oracleId), { recursive: true });
  appendFileSync(lookupsPath(oracleId), JSON.stringify({ at: new Date().toISOString(), ...rec }) + '\n', 'utf8');
}

export function loadLookups(oracleId: string): LookupRecord[] {
  const path = lookupsPath(oracleId);
  if (!existsSync(path)) return [];
  return readFileSync(path, 'utf8')
    .split('\n')
    .filter((l) => l.trim().length > 0)
    .map((l) => JSON.parse(l) as LookupRecord);
}

