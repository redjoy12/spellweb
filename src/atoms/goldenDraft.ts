/**
 * Assisted golden-set drafting: the staging layer between an assistant drafter
 * and `golden_atoms` (plan Task 6, Step 5 — amended; see `docs/golden-set-procedure.md`,
 * "Assisted drafting").
 *
 * WHY THIS IS ALLOWED TO EXIST. `golden.ts` states, correctly, that it never
 * drafts or synthesizes golden content. This module does not either: it builds
 * the *materials* a drafter reads, records what the drafter actually read, and
 * validates what the drafter proposes. The spec sanctions an assistant here and
 * names the condition that makes it safe (sec. 2, "The one place human-and-assistant
 * work is correct is the golden set — low volume, high judgement, human-verified";
 * sec. 12 risk "Golden set inherits assistant assumptions" -> mitigation "Human
 * verification before entry"). Two properties carry that:
 *
 *  1. NOTHING UNVERIFIED REACHES THE DATABASE. Proposals are files under
 *     `data/golden-drafts/`, deliberately NOT a table. `golden_atoms` is written
 *     by exactly one function here (`acceptProposal`), which requires the owner's
 *     explicit acceptance and goes through `upsertGoldenCard`'s own validation.
 *     Task 7 (kernel), Task 9 (extraction) and Task 10 (bake-off) read the DB, so
 *     an un-adjudicated proposal is invisible to every downstream consumer.
 *
 *  2. EVERY CITATION MUST BE READ, NOT RECALLED. The drafting packet carries the
 *     UNGATED term-matched rules with their full text (sec. 8.1: drafted against
 *     the ungated corpus, never the assembled packet — a set drafted inside the
 *     gate's hole cannot see the hole, sec. 3.6). A drafter may legitimately cite
 *     a rule term matching cannot reach ("that difference is exactly what the
 *     kernel captures in Task 7") — but only by LOOKING IT UP, which
 *     `recordLookup` appends to an append-only audit log. `validateProposal`
 *     then rejects any cited rule that was neither in the packet nor looked up:
 *     a citation with no corresponding read is a citation from model memory,
 *     which is the I1 failure this project forbids everywhere else. This is the
 *     drafting-side analogue of sec. 6.3's citation gate.
 *
 * This module makes ZERO model calls. The drafter is the agent driving the CLI.
 */
