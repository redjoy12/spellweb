/** A proposed atom: a golden atom plus the drafter's stated reasoning. */
export interface ProposedAtom {
  face_index: number;
  family: AtomFamily;
  type_key: string;
  params: Record<string, unknown>;
  span_start: number;
  span_end: number;
  quote: string;
  rule_numbers: string[];
  /** Why this clause yields this atom, in terms of the rule text that was read. */
  rationale: string;
}

/** A clause the vocabulary genuinely has no fit for. Never a forced fit. */
export interface ProposedUnclassified {
  face_index: number;
  span_start: number;
  span_end: number;
  quote: string;
  proposed_label: string;
  rationale: string;
}

export interface DraftProposal {
  oracle_id: string;
  /** The hash the draft was made against; a mismatch at accept time is stale. */
  oracle_hash: string;
  schema_version: number;
  /** Who drafted it — an agent identifier, never presented as a human verifier. */
  drafted_by: string;
  drafted_at: string;
  /** The drafter's claim that every non-reminder clause is accounted for. */
  claims_complete: boolean;
  atoms: ProposedAtom[];
  unclassified: ProposedUnclassified[];
  /** Free-text notes for the adjudicator: doubts, alternatives considered. */
  notes: string;
}

export interface ProposalValidation {
  ok: boolean;
  /** Hard failures. A proposal with any of these can never be accepted. */
  errors: string[];
  /** Things the adjudicator should look at, which do not block acceptance. */
  warnings: string[];
  atoms: number;
  unclassified: number;
  non_reminder_clauses: number;
  uncovered_clauses: number;
}

/**
 * Validates a staged proposal WITHOUT writing anything. Three layers:
 *
 *  1. The same per-atom checks `upsertGoldenCard` enforces (quote slices back
 *     verbatim, cited rules exist in the corpus, the type exists at the current
 *     schema_version, params validate) — run here so a bad draft is rejected at
 *     staging time rather than blowing up in the owner's face at accept time.
 *  2. THE READ GATE (see module header): every cited rule must appear in the
 *     card's packet or in its lookup log. A citation nobody read is model memory.
 *  3. Coverage, when the drafter claims completeness: every non-`reminder`
 *     clause overlapped by >= 1 proposed atom or >= 1 unclassified candidate.
 */
export function validateProposal(db: DatabaseSync, proposal: DraftProposal): ProposalValidation {
  const errors: string[] = [];
  const warnings: string[] = [];
  const corpusId = currentCorpusId(db);
  const schemaVersion = currentSchemaVersion(db);

  const card = db
    .prepare('SELECT oracle_hash FROM cards WHERE oracle_id = ?')
    .get(proposal.oracle_id) as { oracle_hash: string } | undefined;
  if (!card) {
    return {
      ok: false, errors: [`no card with oracle_id ${proposal.oracle_id}`], warnings: [],
      atoms: 0, unclassified: 0, non_reminder_clauses: 0, uncovered_clauses: 0,
    };
  }
  if (card.oracle_hash !== proposal.oracle_hash) {
    errors.push(
      `stale draft: proposal oracle_hash ${proposal.oracle_hash} != live ${card.oracle_hash}; re-generate the packet and re-draft`,
    );
  }
  if (proposal.schema_version !== schemaVersion) {
    errors.push(`proposal schema_version ${proposal.schema_version} != current ${schemaVersion}`);
  }

  const faces = db
    .prepare('SELECT face_index, oracle_text FROM card_faces WHERE oracle_id = ? ORDER BY face_index')
    .all(proposal.oracle_id) as Array<{ face_index: number; oracle_text: string }>;
  const textByFace = new Map(faces.map((f) => [f.face_index, f.oracle_text]));

  // Layer 1 — the same per-atom validation upsertGoldenCard enforces.
  proposal.atoms.forEach((a, i) => {
    const tag = `atom #${i} (face ${a.face_index} ${a.family}.${a.type_key})`;
    if (!textByFace.has(a.face_index)) {
      errors.push(`${tag}: no card_faces row for face_index ${a.face_index}`);
      return;
    }
    errors.push(...validateGoldenAtom(db, tag, textByFace.get(a.face_index) ?? '', a, corpusId, schemaVersion));
    if (!a.rationale || a.rationale.trim().length === 0) {
      errors.push(`${tag}: empty rationale — an unexplained atom cannot be adjudicated`);
    }
  });

  // Layer 1b — the storage key. `golden_atoms` is uniquely indexed on
  // (oracle_id, face_index, family, type_key, span_start), so two atoms of the
  // same type at the same offset cannot both be written however different their
  // params are. Without this check a proposal stages VALID and then dies on a raw
  // SQLite constraint error mid-`--accept`, which is the failure mode this whole
  // file exists to prevent: validation must reject before the write, not leave
  // the database to. The fix at drafting time is almost always a narrower span —
  // point each atom at the substring it actually describes.
  const byKey = new Map<string, number[]>();
  proposal.atoms.forEach((a, i) => {
    const key = `${a.face_index}|${a.family}|${a.type_key}|${a.span_start}`;
    byKey.set(key, [...(byKey.get(key) ?? []), i]);
  });
  for (const [key, idx] of byKey) {
    if (idx.length < 2) continue;
    const [faceIndex, family, typeKey, spanStart] = key.split('|');
    errors.push(
      `atoms #${idx.join(', #')}: duplicate storage key (face ${faceIndex} ${family}.${typeKey} ` +
        `span_start ${spanStart}) — golden_atoms is uniquely indexed on it, so only one of these ` +
        'could ever be written. Give each atom the span of the text it describes, or merge them.',
    );
  }

  proposal.unclassified.forEach((u, i) => {
    const tag = `unclassified #${i} (face ${u.face_index})`;
    const faceText = textByFace.get(u.face_index);
    if (faceText === undefined) {
      errors.push(`${tag}: no card_faces row for face_index ${u.face_index}`);
      return;
    }
    if (faceText.slice(u.span_start, u.span_end) !== u.quote) {
      errors.push(`${tag}: quote does not slice back from card_faces.oracle_text`);
    }
    if (!u.proposed_label.trim()) errors.push(`${tag}: empty proposed_label`);
    if (!u.rationale.trim()) errors.push(`${tag}: empty rationale`);
  });

  // Layer 2 — the read gate. A cited rule must have been in the packet or looked up.
  const packet = readPacket(proposal.oracle_id);
  const readable = new Set<string>();
  for (const r of packet?.rules ?? []) readable.add(r.number);
  for (const l of loadLookups(proposal.oracle_id)) for (const n of l.returned) readable.add(n);
  if (!packet) {
    warnings.push('no packet.json on disk: the read gate can only see the lookup log for this card');
  }
  const unread = new Set<string>();
  for (const a of proposal.atoms) for (const n of a.rule_numbers) if (!readable.has(n)) unread.add(n);
  if (unread.size > 0) {
    errors.push(
      `cited without reading (I1): ${[...unread].sort().join(', ')} — these rules are neither in ` +
        "this card's packet nor in its lookup log. Look them up " +
        '(npm run golden:draft -- --lookup <oracle_id> <rule>) and re-draft, or drop the citation. ' +
        'A rule number produced from memory is exactly what the project forbids.',
    );
  }
  // A citation term matching could not reach is legitimate and interesting — it is
  // what Task 7 derives the kernel from — but the adjudicator should see it named.
  const beyondTermMatch = new Set<string>();
  const inPacket = new Set((packet?.rules ?? []).map((r) => r.number));
  for (const a of proposal.atoms) {
    for (const n of a.rule_numbers) if (readable.has(n) && !inPacket.has(n)) beyondTermMatch.add(n);
  }
  if (beyondTermMatch.size > 0) {
    warnings.push(`cited beyond term match (kernel candidates, sec. 3.4): ${[...beyondTermMatch].sort().join(', ')}`);
  }

  // Layer 3 — coverage, only meaningful against a completeness claim.
  let nonReminder = 0;
  let uncovered = 0;
  for (const f of faces) {
    for (const c of splitOracleText(f.oracle_text, f.face_index)) {
      if (c.kind === 'reminder') continue;
      nonReminder++;
      const covered =
        proposal.atoms.some((a) => a.face_index === f.face_index && overlaps(a, c)) ||
        proposal.unclassified.some((u) => u.face_index === f.face_index && overlaps(u, c));
      if (!covered) {
        uncovered++;
        if (proposal.claims_complete) {
          errors.push(`claims_complete but clause [${c.clause_index}] on face ${f.face_index} is uncovered: "${c.text}"`);
        } else {
          warnings.push(`uncovered clause [${c.clause_index}] face ${f.face_index}: "${c.text}"`);
        }
      }
    }
  }

  return {
    ok: errors.length === 0,
    errors,
    warnings,
    atoms: proposal.atoms.length,
    unclassified: proposal.unclassified.length,
    non_reminder_clauses: nonReminder,
    uncovered_clauses: uncovered,
  };
}

function overlaps(
  a: { span_start: number; span_end: number },
  c: { span_start: number; span_end: number },
): boolean {
  return Math.max(0, Math.min(a.span_end, c.span_end) - Math.max(a.span_start, c.span_start)) > 0;
}

export function writeProposal(proposal: DraftProposal): string {
  mkdirSync(cardDir(proposal.oracle_id), { recursive: true });
  const path = proposalPath(proposal.oracle_id);
  writeFileSync(path, JSON.stringify(proposal, null, 2) + '\n', 'utf8');
  return path;
}

export function readProposal(oracleId: string): DraftProposal | undefined {
  const path = proposalPath(oracleId);
  if (!existsSync(path)) return undefined;
  return JSON.parse(readFileSync(path, 'utf8')) as DraftProposal;
}

// --------------------------------------------------------------------------- adjudication

/** One proposed item the owner struck out during review, kept for the audit trail. */
export interface ExcludedItem {
  kind: 'atom' | 'unclassified';
  /** Index into the STAGED proposal's array — the draft on disk is never rewritten. */
  index: number;
  /** Human-readable identity of what was struck, so the record survives a re-draft. */
  summary: string;
}

export interface ReviewRecord {
  oracle_id: string;
  decision: 'accepted' | 'rejected';
  /** The owner's own completeness call, which overrides the drafter's claim. */
  complete: boolean;
  reviewed_at: string;
  note: string;
  /**
   * Atoms/unclassified candidates the owner declined while accepting the rest.
   * Optional: reviews written before per-item exclusion existed have no field,
   * and an empty exclusion is not recorded as one.
   */
  excluded?: ExcludedItem[];
}

export function readReview(oracleId: string): ReviewRecord | undefined {
  const path = reviewPath(oracleId);
  if (!existsSync(path)) return undefined;
  return JSON.parse(readFileSync(path, 'utf8')) as ReviewRecord;
}

function writeReview(rec: ReviewRecord): void {
  mkdirSync(cardDir(rec.oracle_id), { recursive: true });
  writeFileSync(reviewPath(rec.oracle_id), JSON.stringify(rec, null, 2) + '\n', 'utf8');
}

/**
 * THE ONLY PATH from a staged proposal into `golden_cards` / `golden_atoms`.
 * Called exclusively by `--accept`, which is the owner's act (sec. 8.1: "verified
 * by the project owner, card by card, before it is written"). Re-validates first
 * and throws on any failure, then delegates to `upsertGoldenCard`, which
 * validates again and writes transactionally.
 *
 * `complete` is the OWNER's call, not the drafter's `claims_complete`: a card
 * whose atoms are individually right but whose coverage the owner has not
 * personally confirmed belongs in the set as an honest partial (sec. 8.2 computes
 * precision over complete cards only, so a partial costs nothing and a wrongly
 * complete card corrupts the metric).
 *
 * `opts.exclude` strikes individual proposed items without rejecting the card.
 * One wrong atom used to cost the whole draft a round trip, which pushed toward
 * accepting a doubtful atom to save the good ones — the opposite of what this
 * gate is for. What is written is the EFFECTIVE proposal (the staged one minus
 * the struck items); the file on disk is never rewritten, so the draft and the
 * decision about it stay separately readable. Every exclusion is named in the
 * review record, and excluding anything requires a note.
 *
 * Validation runs against that effective proposal with `claims_complete` set to
 * the OWNER's `complete`: at accept time the drafter's claim is spent (it was
 * surfaced at staging), and leaving it in would let a drafter's overclaim block
 * an honest partial acceptance.
 */
export function acceptProposal(
  db: DatabaseSync,
  oracleId: string,
  opts: {
    complete: boolean;
    note?: string;
    exclude?: { atoms?: number[]; unclassified?: number[] };
  },
): { atoms: number; unclassified: number; excluded: ExcludedItem[] } {
  const proposal = readProposal(oracleId);
  if (!proposal) throw new Error(`no staged proposal for ${oracleId}`);

  const excluded = resolveExclusions(proposal, opts.exclude);
  if (excluded.length > 0 && !opts.note?.trim()) {
    throw new Error(
      `acceptProposal(${oracleId}): striking ${excluded.length} proposed item(s) requires a note saying why`,
    );
  }
  const struckAtoms = new Set(excluded.filter((e) => e.kind === 'atom').map((e) => e.index));
  const struckUnclassified = new Set(excluded.filter((e) => e.kind === 'unclassified').map((e) => e.index));

  const effective: DraftProposal = {
    ...proposal,
    claims_complete: opts.complete,
    atoms: proposal.atoms.filter((_, i) => !struckAtoms.has(i)),
    unclassified: proposal.unclassified.filter((_, i) => !struckUnclassified.has(i)),
  };
  // An empty card asserts "this card yields no atoms". Whether that is a refusal
  // or the whole point depends on WHERE the emptiness came from:
  //
  //  - emptied by exclusions — the owner struck every proposed item, so the
  //    drafter's reading was wrong and there is nothing to stand behind. Refuse:
  //    the draft goes back for redrafting rather than being written as a claim
  //    nobody made.
  //  - empty as drafted — the drafter proposed nothing because the card has
  //    nothing to propose (a vanilla creature: `oracle_text` is the empty
  //    string, so the face yields zero clauses). Then "yields no atoms" is the
  //    correct and useful ground truth, and `scoreRun` already relies on it:
  //    goldenTotal gains nothing, while `accepted` still counts every atom a
  //    run emitted on the card, so a hallucinated atom is a pure false positive
  //    against sec. 8.2 precision. Refusing here would make the one card shape
  //    that tests for invention unrepresentable.
  if (effective.atoms.length === 0 && effective.unclassified.length === 0 && excluded.length > 0) {
    throw new Error(
      `acceptProposal(${oracleId}): nothing left after exclusions — reject the draft instead of ` +
        'accepting an empty card, which would assert a reading the draft no longer contains',
    );
  }

  const validation = validateProposal(db, effective);
  if (!validation.ok) {
    throw new Error(
      `acceptProposal(${oracleId}): proposal does not validate, nothing written:\n  ${validation.errors.join('\n  ')}`,
    );
  }
  if (opts.complete && validation.uncovered_clauses > 0) {
    throw new Error(
      `acceptProposal(${oracleId}): accepting as complete, but ${validation.uncovered_clauses} non-reminder clause(s) are uncovered`,
    );
  }

  const verifiedAt = new Date().toISOString();
  const atoms: GoldenAtom[] = effective.atoms.map((a) => ({
    face_index: a.face_index,
    schema_version: proposal.schema_version,
    family: a.family,
    type_key: a.type_key,
    params: a.params,
    span_start: a.span_start,
    span_end: a.span_end,
    quote: a.quote,
    rule_numbers: a.rule_numbers,
    source: 'authored',
  }));

  upsertGoldenCard(db, {
    oracle_id: proposal.oracle_id,
    complete: opts.complete,
    oracle_hash: proposal.oracle_hash,
    verified_at: verifiedAt,
    atoms,
  });

  // Accepting is idempotent for atoms - upsertGoldenCard deletes this card's golden_atoms before
  // reinserting - and must be for unclassified candidates too. Without this delete, re-accepting a
  // card (a redraft, a correction, an errata re-adjudication) APPENDED a second copy of every
  // candidate: 199 of the 453 rows in the table were exact duplicates when this was found. That is
  // not cosmetic - sec. 4.3 promotes "a recurring one" and sec. 7.4 ranks the review queue by these
  // rows, so a duplicate makes a gap look twice as recurring as it is and can drive a promotion the
  // evidence does not support. Scoped to (run_id, oracle_id): Task 9's model runs write to this
  // same table for the same oracle_id under a different run_id, and must not be touched here - the
  // same scoping verifyGoldenCard's coverage lookup already depends on.
  db.prepare('DELETE FROM unclassified_clauses WHERE run_id = ? AND oracle_id = ?')
    .run(goldenDraftingRunId(db), proposal.oracle_id);

  for (const u of effective.unclassified) {
    recordUnclassifiedCandidate(db, {
      oracle_id: proposal.oracle_id,
      face_index: u.face_index,
      span_start: u.span_start,
      span_end: u.span_end,
      quote: u.quote,
      proposed_label: u.proposed_label,
      rationale: u.rationale,
      oracle_hash: proposal.oracle_hash,
    });
  }

  writeReview({
    oracle_id: oracleId,
    decision: 'accepted',
    complete: opts.complete,
    reviewed_at: verifiedAt,
    note: opts.note ?? '',
    ...(excluded.length > 0 ? { excluded } : {}),
  });

  return { atoms: atoms.length, unclassified: effective.unclassified.length, excluded };
}

/**
 * Turns index lists into named exclusions, rejecting anything out of range: a
 * stale index (a UI built against an older draft, a hand-written request) would
 * otherwise silently strike the wrong atom, and the review record would name an
 * item the owner never saw.
 */
function resolveExclusions(
  proposal: DraftProposal,
  exclude: { atoms?: number[]; unclassified?: number[] } | undefined,
): ExcludedItem[] {
  const out: ExcludedItem[] = [];
  const check = (i: unknown, len: number, kind: string): number => {
    if (typeof i !== 'number' || !Number.isInteger(i) || i < 0 || i >= len) {
      throw new Error(`exclude.${kind}: ${String(i)} is not an index into this proposal's ${len} ${kind}`);
    }
    return i;
  };
  for (const i of new Set(exclude?.atoms ?? [])) {
    const idx = check(i, proposal.atoms.length, 'atoms');
    const a = proposal.atoms[idx]!;
    out.push({ kind: 'atom', index: idx, summary: `${a.family}.${a.type_key} "${a.quote}"` });
  }
  for (const i of new Set(exclude?.unclassified ?? [])) {
    const idx = check(i, proposal.unclassified.length, 'unclassified');
    const u = proposal.unclassified[idx]!;
    out.push({ kind: 'unclassified', index: idx, summary: `${u.proposed_label} "${u.quote}"` });
  }
  return out;
}

export function rejectProposal(oracleId: string, note: string): void {
  if (!readProposal(oracleId)) throw new Error(`no staged proposal for ${oracleId}`);
  writeReview({
    oracle_id: oracleId,
    decision: 'rejected',
    complete: false,
    reviewed_at: new Date().toISOString(),
    note,
  });
}

// --------------------------------------------------------------------------- ledger

export type DraftStage = 'not-started' | 'packet' | 'drafted' | 'accepted' | 'rejected';

export interface LedgerEntry {
  oracle_id: string;
  name: string;
  stage: DraftStage;
  atoms: number;
  unclassified: number;
  lookups: number;
}

/** Reads the staging directory. Pure disk state; no DB writes. */
export function ledger(candidates: Array<{ oracle_id: string; name: string }>): LedgerEntry[] {
  const known = new Map(candidates.map((c) => [c.oracle_id, c.name]));
  // Directories only: the staging root also holds the shared vocabulary.json.
  const onDisk = existsSync(draftsDir())
    ? readdirSync(draftsDir()).filter((e) => statSync(join(draftsDir(), e)).isDirectory())
    : [];
  for (const id of onDisk) if (!known.has(id)) known.set(id, '(not in candidate list)');

  return [...known.entries()].map(([oracle_id, name]) => {
    const review = readReview(oracle_id);
    const proposal = readProposal(oracle_id);
    // A proposal re-staged AFTER its review was written is an un-adjudicated draft again, even
    // though a review.json exists. Without this, the first sec. 4.3 promotion made 9 accepted
    // cards silently stale: their v1 atoms used a type v2 retired, --verify rejected them, and
    // the redrafts sat on disk reading `accepted` in the queue, so the owner would never have
    // been shown them. The review file is deliberately left in place - it is the record of the
    // earlier decision, and the redraft does not undo that it was made.
    const restaged = !!review && !!proposal && proposal.drafted_at > review.reviewed_at;
    const stage: DraftStage = review && !restaged
      ? review.decision
      : proposal
        ? 'drafted'
        : existsSync(packetPath(oracle_id))
          ? 'packet'
          : 'not-started';
    return {
      oracle_id,
      name,
      stage,
      atoms: proposal?.atoms.length ?? 0,
      unclassified: proposal?.unclassified.length ?? 0,
      lookups: loadLookups(oracle_id).length,
    };
  });
}
